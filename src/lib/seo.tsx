import type { Metadata } from "next";

import { site } from "@/config/site";

/**
 * Per-page metadata helper.
 *
 * Every indexable page calls `pageMetadata()` so title, description, canonical
 * and OpenGraph are handled one way. The title template (`%s | <name>`) lives in
 * the root layout, so pages pass only their own title.
 *
 * The canonical URL is derived from the route, not hand-written, which removes a
 * whole class of duplicate-content mistakes.
 */
export function pageMetadata(input: {
  title: string;
  description: string;
  /** Route path, e.g. "/services/neurotoxins". Use "/" for home. */
  path: string;
  image?: { url: string; width: number; height: number; alt: string };
  /** Set false for pages that should not be indexed (none currently). */
  index?: boolean;
}): Metadata {
  const url = absoluteUrl(input.path);
  // `url` is listed last so an absolute URL always wins over the caller's
  // relative one, while width/height/alt are taken from the caller.
  // Pages that pass no image fall back to the site-wide card, so every indexable
  // page has a share image — a missing og:image means a blank social card.
  const image = { ...DEFAULT_OG_IMAGE, ...(input.image ?? {}) };
  image.url = absoluteUrl(image.url);

  return {
    title: input.title,
    description: input.description,
    alternates: { canonical: url },
    openGraph: {
      title: `${input.title} | ${site.name}`,
      description: input.description,
      url,
      siteName: site.name,
      type: "website",
      images: [image],
    },
    twitter: {
      card: "summary_large_image",
      title: `${input.title} | ${site.name}`,
      description: input.description,
      images: [image.url],
    },
    robots: {
      index: input.index ?? true,
      follow: input.index ?? true,
    },
  };
}

/**
 * Site-wide share image. Generated by `scripts/gen-og-image.mjs` from the site's
 * own CSS and self-hosted fonts, so it can never drift from the branding.
 */
const DEFAULT_OG_IMAGE = {
  url: "/og-image.png",
  width: 1200,
  height: 630,
  alt: `${site.name} — ${site.seo.description}`,
};

export function absoluteUrl(path: string): string {
  const base = site.seo.url.replace(/\/$/, "");
  return `${base}${path.startsWith("/") ? path : `/${path}`}` || base;
}

// ---------------------------------------------------------------------------
// Structured data
//
// Only values that are actually configured are emitted. A field that is null in
// config is omitted rather than filled with an invented value, so the markup
// can never claim something the business has not stated.
// ---------------------------------------------------------------------------

type Json = Record<string, unknown>;

export function organizationSchema(): Json {
  const schema: Json = {
    "@context": "https://schema.org",
    "@type": "Organization",
    name: site.name,
    url: site.seo.url,
    logo: absoluteUrl(site.logo.src),
    description: site.seo.description,
    sameAs: site.socials.map((s) => s.href),
  };
  if (site.contact.email) schema.email = site.contact.email;
  if (site.contact.phone) schema.telephone = site.contact.phone;
  return schema;
}

/** LocalBusiness, emitted only once name/address/phone are actually configured. */
export function localBusinessSchema(studio: {
  name: string;
  streetAddress: string;
  addressLocality: string;
  phone: string | null;
  mapUrl: string | null;
}): Json | null {
  // A local business claim needs a real address and a way to reach it. Without
  // both, emitting the schema would be a fabricated claim, so we return null.
  if (!studio.streetAddress || !studio.phone) return null;

  return {
    "@context": "https://schema.org",
    "@type": "MedicalBusiness",
    name: `${site.name} — ${studio.name}`,
    parentOrganization: { "@type": "Organization", name: site.name },
    url: absoluteUrl(`/locations#${studio.name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`),
    telephone: studio.phone,
    address: {
      "@type": "PostalAddress",
      streetAddress: studio.streetAddress,
      addressLocality: studio.addressLocality,
    },
  };
}

export function serviceSchema(s: {
  name: string;
  description: string;
  path: string;
}): Json {
  return {
    "@context": "https://schema.org",
    "@type": "Service",
    name: s.name,
    description: s.description,
    serviceType: s.name,
    url: absoluteUrl(s.path),
    provider: { "@type": "Organization", name: site.name },
  };
}

export function breadcrumbSchema(crumbs: { name: string; path: string }[]): Json {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: crumbs.map((c, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: c.name,
      item: absoluteUrl(c.path),
    })),
  };
}

export function faqSchema(items: { q: string; a: string }[]): Json | null {
  if (!items.length) return null;
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: items.map((i) => ({
      "@type": "Question",
      name: i.q,
      acceptedAnswer: { "@type": "Answer", text: i.a },
    })),
  };
}

export function articleSchema(p: {
  title: string;
  description: string;
  path: string;
  image: { url: string };
}): Json {
  return {
    "@context": "https://schema.org",
    "@type": "Article",
    headline: p.title,
    description: p.description,
    url: absoluteUrl(p.path),
    image: absoluteUrl(p.image.url),
    publisher: { "@type": "Organization", name: site.name },
  };
}

/**
 * Renders a JSON-LD block. Next dedupes identical script tags only by
 * key/identity, so a stable id is included for each graph node.
 */
export function JsonLd({ id, data }: { id: string; data: Json | Json[] | null }) {
  if (!data) return null;
  const payload = Array.isArray(data) ? data : [data];
  return (
    <script
      type="application/ld+json"
      id={id}
      // Serialised with < escaped so a string containing "</script>" cannot
      // terminate the tag early.
      dangerouslySetInnerHTML={{
        __html: JSON.stringify(payload.length === 1 ? payload[0] : payload).replace(/</g, "\\u003c"),
      }}
    />
  );
}
